class ThaiInstitution {
  const ThaiInstitution({
    required this.id,
    required this.storedName,
    required this.shortLabel,
    required this.nameTh,
    required this.nameEn,
    required this.category,
    required this.defaultType,
    required this.primaryHex,
    required this.secondaryHex,
    required this.fallbackIconKey,
    required this.motif,
    this.accentHex,
    this.darkInk = false,
    this.popular = false,
    this.aliases = const <String>[],
  });

  final String id;
  final String storedName;
  final String shortLabel;
  final String nameTh;
  final String nameEn;
  final ThaiInstitutionCategory category;
  final AccountType defaultType;
  final String primaryHex;
  final String secondaryHex;
  final String? accentHex;
  final bool darkInk;
  final bool popular;
  final String fallbackIconKey;
  final EmblemMotif motif;
  final List<String> aliases;

  bool matchesQuery(String query) {
    final String q = query.trim().toLowerCase();
    if (q.isEmpty) {
      return true;
    }
    if (id.toLowerCase().contains(q) ||
        storedName.toLowerCase().contains(q) ||
        shortLabel.toLowerCase().contains(q) ||
        nameTh.toLowerCase().contains(q) ||
        nameEn.toLowerCase().contains(q)) {
      return true;
    }
    for (final String alias in aliases) {
      if (alias.toLowerCase().contains(q)) {
        return true;
      }
    }
    return false;
  }
}

