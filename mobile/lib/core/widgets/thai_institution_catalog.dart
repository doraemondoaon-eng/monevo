  static List<ThaiInstitution> filter({
    String query = '',
    ThaiInstitutionCategory? category,
  }) {
    final Iterable<ThaiInstitution> byCategory = category == null
        ? all
        : all.where((ThaiInstitution i) => i.category == category);
    if (query.trim().isEmpty) {
      return byCategory.toList(growable: false);
    }
    return byCategory
        .where((ThaiInstitution i) => i.matchesQuery(query))
        .toList(growable: false);
  }

  /// Resolves a [ThaiInstitution] from `institution` first, or falls back to
  /// `accountName` when `institution` is empty. Uses exact matches first and then
  /// longest alias/name match to prevent short-code collisions (e.g. `LINE BK` vs `LINE Pay`).
  static ThaiInstitution? match(
    String? institution, {
    String? accountName,
  }) {
    final String primary = (institution ?? '').trim();
    if (primary.isNotEmpty) {
      final ThaiInstitution? exactOrScored = _matchText(primary);
      if (exactOrScored != null) {
        return exactOrScored;
      }
    }
    final String secondary = (accountName ?? '').trim();
    if (primary.isEmpty && secondary.isNotEmpty) {
      return _matchText(secondary);
    }
    return null;
  }

  static ThaiInstitution? _matchText(String rawText) {
    final String normalized = rawText.trim().toLowerCase();
    if (normalized.isEmpty) {
      return null;
    }

    // 1. Exact match on storedName, id, shortLabel, nameTh, nameEn, or alias
    for (final ThaiInstitution item in all) {
      if (item.storedName.toLowerCase() == normalized ||
          item.id.toLowerCase() == normalized ||
          item.shortLabel.toLowerCase() == normalized ||
          item.nameTh.toLowerCase() == normalized ||
          item.nameEn.toLowerCase() == normalized) {
        return item;
      }
      for (final String alias in item.aliases) {
        if (alias.toLowerCase() == normalized) {
          return item;
        }
      }
    }

    // 2. Longest specific substring match (preferring more specific phrases like
    // "first choice" or "krungsri auto" over generic "krungsri").
    ThaiInstitution? bestMatch;
    int bestLength = 0;

    for (final ThaiInstitution item in all) {
      final List<String> candidates = <String>[
        item.storedName,
        item.nameTh,
        item.nameEn,
        item.shortLabel,
        ...item.aliases,
      ];
      for (final String candidate in candidates) {
        final String key = candidate.trim().toLowerCase();
        if (key.length < 2) {
          continue;
        }
        if (_containsTokenSafe(normalized, key) && key.length > bestLength) {
          bestMatch = item;
          bestLength = key.length;
        }
      }
    }
    return bestMatch;
  }

  static bool _containsTokenSafe(String haystack, String needle) {
    final int idx = haystack.indexOf(needle);
    if (idx < 0) {
      return false;
    }
    // For very short ASCII codes (<= 4 chars like scb, bbl, ktb, ktc, bay, uob),
    // verify word boundaries so unrelated words like "set" don't false-match inside "reset".
    final bool isShortAscii =
        needle.length <= 4 && RegExp(r'^[a-z0-9+]+$').hasMatch(needle);
    if (!isShortAscii) {
      return true;
    }
    final bool startOk =
        idx == 0 || !RegExp(r'[a-z0-9]').hasMatch(haystack[idx - 1]);
    final int endIdx = idx + needle.length;
    final bool endOk =
        endIdx >= haystack.length ||
        !RegExp(r'[a-z0-9]').hasMatch(haystack[endIdx]);
    return startOk && endOk;
  }
