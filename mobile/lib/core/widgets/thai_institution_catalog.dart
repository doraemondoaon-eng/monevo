  stateBank('ธนาคารของรัฐ', 'State Banks'),
  creditCard('บัตรเครดิต / กดเงินสด', 'Credit & Cash Cards'),
  personalLoan('สินเชื่อส่วนบุคคล / ผ่อนจ่าย', 'Personal & Digital Loans'),
  assetLoan('สินเชื่อรถ บ้าน & สหกรณ์', 'Auto, Home, SLF & Co-op'),
  eWallet('อีวอลเล็ท / ชำระเงิน', 'E-Wallets & Payments'),
  investment('ลงทุน / หุ้น / คริปโต', 'Investments & Crypto');

  const ThaiInstitutionCategory(this.labelTh, this.labelEn);

